/** Index memberships the filter offers (NIFTY 50 from the shipped list). */
const INDEX_MEMBERS = {
  "NIFTY 50": NIFTY50.map((s) => s.split(":")[1]),
  "NIFTY BANK": "HDFCBANK ICICIBANK SBIN KOTAKBANK AXISBANK INDUSINDBK BANKBARODA PNB AUBANK IDFCFIRSTB FEDERALBNK CANBK".split(" "),
  "NIFTY IT": "TCS INFY HCLTECH WIPRO TECHM LTIM PERSISTENT COFORGE MPHASIS OFSS".split(" "),
};

/** ticker -> sector */
const SECTOR = new Map();
for (const [sector, list] of Object.entries(BY_SECTOR)) for (const t of list.split(" ")) if (!SECTOR.has(t)) SECTOR.set(t, sector);

/** Every F&O stock this list knows (demo mode scans these). */
export const FNO_STOCKS = Object.freeze([...SECTOR.keys()].sort());
export const INDEX_NAMES = Object.freeze(Object.keys(INDEX_MEMBERS));

const tickerOf = (symbol) => String(symbol ?? "").split(":").pop().toUpperCase();

/** { sector, indices } for a symbol ("NSE:RELIANCE" or "RELIANCE"). */
export function symbolMeta(symbol) {
  const t = tickerOf(symbol);
  return { sector: SECTOR.get(t) ?? null, indices: INDEX_NAMES.filter((i) => INDEX_MEMBERS[i].includes(t)) };
}

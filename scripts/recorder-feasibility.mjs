#!/usr/bin/env node
/**
 * Prints the recorder feasibility table (docs/spec/p1-01-recorder.md §5.2–5.3) as Markdown, generated from the code:
 * the broker policy table (server/bridge/ratelimit/brokerPolicies.mjs), each adapter's declared feed, and the
 * recorder planner (server/bridge/recorder/plan.mjs) with the default `recorder` config. One row per adapter (all of
 * server/brokers/registry.mjs) plus the demo broker.
 *
 *   node scripts/recorder-feasibility.mjs           print the table
 *   node scripts/recorder-feasibility.mjs --write   replace the table in docs/guides/recorder.md
 *
 * plan.test.mjs checks that the table in docs/guides/recorder.md equals this output, so the doc cannot drift.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { declaredCapabilities } from "../server/brokers/contract.mjs";
import { createBrokerRegistry } from "../server/brokers/registry.mjs";
import { BROKER_NAMES } from "../server/bridge/accounts/brokerInfo.mjs";
import { DEMO_POLICY } from "../server/bridge/demo/demoMode.mjs";
import { resolvePolicy } from "../server/bridge/ratelimit/policy.mjs";
import { parseRecorderConfig } from "../server/bridge/recorder/config.mjs";
import { feasibilityMarkdown, feasibilityRow } from "../server/bridge/recorder/plan.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const DOC = resolve(ROOT, "docs/guides/recorder.md");
export const START = "<!-- feasibility:start (generated by scripts/recorder-feasibility.mjs; do not edit by hand) -->";
export const END = "<!-- feasibility:end -->";

/** The rows for every adapter plus demo. */
export function feasibilityRows() {
  const cfg = parseRecorderConfig({});
  const registry = createBrokerRegistry();
  const rows = registry
    .list()
    .map((id) => feasibilityRow({ broker: id, policy: resolvePolicy(id), hasFeed: declaredCapabilities(registry.get(id)).includes("feed"), cfg, label: BROKER_NAMES[id] ?? id }))
    .sort((a, b) => a.label.localeCompare(b.label));
  rows.push(feasibilityRow({ broker: "demo", policy: resolvePolicy("demo", {}, { demo: DEMO_POLICY }), hasFeed: true, cfg, label: "Demo (sample data)" }));
  return rows;
}

/** The Markdown table. */
export function feasibilityTable() {
  return feasibilityMarkdown(feasibilityRows());
}

/** The table currently in the doc (between the markers), or null. */
export function tableInDoc(text = readFileSync(DOC, "utf8")) {
  const a = text.indexOf(START);
  const b = text.indexOf(END);
  if (a < 0 || b < a) return null;
  return text.slice(a + START.length, b).trim();
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const table = feasibilityTable();
  if (process.argv.includes("--write")) {
    const text = readFileSync(DOC, "utf8");
    const a = text.indexOf(START);
    const b = text.indexOf(END);
    if (a < 0 || b < a) throw new Error(`Markers not found in ${DOC}`);
    writeFileSync(DOC, `${text.slice(0, a + START.length)}\n${table}\n${text.slice(b)}`);
    console.log(`Wrote the feasibility table (${table.split("\n").length - 2} rows) to ${DOC}`);
  } else console.log(table);
}

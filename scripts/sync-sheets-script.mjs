#!/usr/bin/env node
// The dashboard's "Copy the Apps Script" button needs the text of integrations/google-sheets/bridge.gs, but the
// dashboard can only load files from its own folder. This writes server/bridge/dashboard/sheets-script.js from the
// real file. Run it after editing bridge.gs (a test fails when the two differ).
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const source = readFileSync(new URL("integrations/google-sheets/bridge.gs", root), "utf8");
if (source.includes("`") || source.includes("${")) throw new Error("bridge.gs must not contain a backtick or ${ (it is embedded in a template string)");
const out = `// sheets-script.js: the Google Sheets Apps Script (integrations/google-sheets/bridge.gs) as text, for the dashboard's
// "Copy the Apps Script" button. GENERATED by scripts/sync-sheets-script.mjs: edit bridge.gs, then run
// \`node scripts/sync-sheets-script.mjs\` (a test fails when this copy is out of date).
export const APPS_SCRIPT = String.raw\`${source}\`;
`;
writeFileSync(new URL("server/bridge/dashboard/sheets-script.js", root), out);
console.log("Wrote server/bridge/dashboard/sheets-script.js");
